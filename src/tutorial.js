// Грани по клеткам: [лицо, изнанка] → плоский массив faces.
function faces(cells) {
  return cells.flatMap(([front, back]) => [
    { color: front[0], letter: front[1] ?? '' },
    { color: back[0], letter: back[1] ?? '' },
  ]);
}

