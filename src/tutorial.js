// Обучение: три мини-уровня, каждый учит одной вещи.
//   1. Сгиб переворачивает часть — сверху оказывается её изнанка (уголок).
//   2. Длинную часть можно загнуть на короткую — она свесится; полоска
//      укорачивается до длины образца.
//   3. Два сгиба подряд: после сгиба клетки лежат стопкой.
//
// crease — единственная линия, которую можно трогать (null — любые);
// side   — какую часть подсвечивать ('start' — левую, 'end' — правую).

import { generateLevel } from './generator.js';
